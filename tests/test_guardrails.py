def test_customer_service_contacts_is_leakage():
    """D-016: measured evidence that the field is post-outcome. Keep this as a
    regression guard — if it ever becomes predictive-lag-free the decision changes."""
    pol = pd.read_parquet(DATA / "policies_motor.parquet",
                          columns=["row_id", "policy_id", "period_start", "period_end",
                                   "customer_service_contacts"])
    pol["ps"] = pd.to_datetime(pol["period_start"])
    pol["pe"] = pd.to_datetime(pol["period_end"])
    claims = pd.read_parquet(DATA / "claims.parquet", columns=["policy_id", "loss_date", "status"])
    claims = claims[claims["status"] != "repudiated"].copy()
    claims["loss"] = pd.to_datetime(claims["loss_date"])
    m = pol.merge(claims, on="policy_id", how="inner")
    m = m[(m["loss"] >= m["ps"]) & (m["loss"] <= m["pe"])]
    claimant_ids = set(m["row_id"])
    pol["has_claim"] = pol["row_id"].isin(claimant_ids)
    ratio = (pol.groupby("has_claim")["customer_service_contacts"].mean())
    assert ratio[True] > 3 * ratio[False], (
        f"expected contact counts to be claim-driven, got {ratio.to_dict()}"
    )


