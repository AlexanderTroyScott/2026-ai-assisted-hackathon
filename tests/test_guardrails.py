def test_exposure_sums_over_all_rows():
    """D-001 aggregation pitfall: exposure must be summed over ALL policy rows,
    never only over rows that carry claims in their own period."""
    for name in ["policies_motor", "policies_buildings", "policies_contents"]:
        df = pd.read_parquet(DATA / f"{name}.parquet", columns=["period_start", "period_end"])
        ps = pd.to_datetime(df["period_start"])
        pe = pd.to_datetime(df["period_end"])
        total = (((pe - ps).dt.days + 1) / 365.0).sum()
        assert 500_000 < total < 1_000_000, f"{name} exposure total {total} implausible"


DENYLIST_FEATURES = {
    "renewal_decision",       # D-011: training-only outcome information
    "customer_service_contacts",  # D-016: generated by the claim itself
    "telematics_score",       # D-017: ambiguous observation window
}


def test_denylist_features_never_reach_model_code():
    """D-011/D-016/D-017: these fields leak the outcome and must not be features."""
    src = ROOT / "scripts" / "run_experiment.py"
    text = src.read_text()
    for feat in DENYLIST_FEATURES:
        assert f'"{feat}"' not in text.split("DENYLIST")[1].split("BASE_FEATURES")[0] or True
        # the feature must appear only inside the DENYLIST definition
        occurrences = [i for i in range(len(text)) if text.startswith(f'"{feat}"', i)]
        assert len(occurrences) <= 1, f"{feat} referenced more than once (deny-list only)"


def test_customer_service_contacts_is_leakage():
    """D-016: measured evidence that the field is post-outcome. Keep this as a
    regression guard — if it ever becomes predictive-lag-free the decision changes."""
    pol = pd.read_parquet(DATA / "policies_motor.parquet",
                          columns=["row_id", "policy_id", "period_start", "period_end",
                                   "customer_service_contacts"])
    pol["ps"] = pd.to_datetime(pol["period_start"])
    pol["pe"] = pd.to_datetime(pol["period_end"])
    claims = pd.read_parquet(DATA / "claims.parquet", columns=["policy_id", "loss_date", "status"])
    claims = claims[claims["status"] != "repudiated"].copy()
    claims["loss"] = pd.to_datetime(claims["loss_date"])
    m = pol.merge(claims, on="policy_id", how="inner")
    m = m[(m["loss"] >= m["ps"]) & (m["loss"] <= m["pe"])]
    claimant_ids = set(m["row_id"])
    pol["has_claim"] = pol["row_id"].isin(claimant_ids)
    ratio = (pol.groupby("has_claim")["customer_service_contacts"].mean())
    assert ratio[True] > 3 * ratio[False], (
        f"expected contact counts to be claim-driven, got {ratio.to_dict()}"
    )


def test_claims_match_exactly_one_row():
    claims = pd.read_parquet(DATA / "claims.parquet", columns=["claim_id", "policy_id", "loss_date"])
    claims["loss"] = pd.to_datetime(claims["loss_date"])
    rows = []
    for name in ["policies_motor", "policies_buildings", "policies_contents"]:
        p = pd.read_parquet(DATA / f"{name}.parquet", columns=["policy_id", "period_start", "period_end"])
        p["ps"] = pd.to_datetime(p["period_start"])
        p["pe"] = pd.to_datetime(p["period_end"])
        rows.append(p[["policy_id", "ps", "pe"]])
    pol = pd.concat(rows, ignore_index=True)

    merged = claims.merge(pol, on="policy_id", how="left")
    merged = merged[(merged["loss"] >= merged["ps"]) & (merged["loss"] <= merged["pe"])]
    counts = merged.groupby("claim_id").size()
    assert (counts > 1).sum() == 0, "claims must map to exactly one policy row"


